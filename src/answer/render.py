"""Rendering the document: markdown, JSON, and the public (gated) shape.

Two rules govern this module:

1. **Attribution is mandatory and unstrippable.** Every export ends with a
   generated attribution section; a renderer that drops it produces a broken
   export, not a cleaner one.
2. **Nothing here reads `source.text`.** Quotes arrive already gated, and spans
   are re-gated at the moment they are turned into text. That is how §3.4's
   "no template formats source.text directly" is kept true in practice.

`public_answer()` is the API boundary: it returns a copy of the answer in which
every span whose policy forbids display has had its text removed. The answer
object stays useful for internal verification (offsets survive), while the
rendered document cannot leak a restricted quote.
"""

from __future__ import annotations

from src import rights
from src.models import (
    Answer,
    Block,
    BlockKind,
    Claim,
    Conflict,
    ConflictKind,
    ContextPack,
    Deepening,
    Source,
    Span,
)

# ═══════════════════════════════════════════════════════════════════════════
# CITATION INDEX
# ═══════════════════════════════════════════════════════════════════════════

def citation_index(answer: Answer) -> dict[str, int]:
    """Stable numbering: order of first citation in the document."""
    order: dict[str, int] = {}
    for block in answer.blocks:
        for source_id in block.source_ids:
            if source_id not in order:
                order[source_id] = len(order) + 1
    for source_id in answer.source_ids:
        if source_id not in order:
            order[source_id] = len(order) + 1
    return order


def _pins(source_ids: list[str], index: dict[str, int]) -> str:
    numbers = sorted({index[sid] for sid in source_ids if sid in index})
    return f" [{', '.join(str(n) for n in numbers)}]" if numbers else ""


# ═══════════════════════════════════════════════════════════════════════════
# MARKDOWN
# ═══════════════════════════════════════════════════════════════════════════

def to_markdown(
    answer: Answer,
    pack: ContextPack,
    sources: dict[str, Source],
    *,
    view: str = "export",
) -> str:
    index = citation_index(answer)
    conflicts = {c.id: c for c in pack.conflicts}
    gaps = {g.id: g for g in pack.gaps}
    lines: list[str] = []

    lines.append(f"# {answer.question}")
    lines.append("")
    if answer.sufficiency.value != "SUFFICIENT":
        lines.append(f"> **{answer.sufficiency.value}.** {answer.sufficiency_note or ''}".rstrip())
        lines.append("")

    for block in answer.blocks:
        lines.extend(_block_markdown(block, answer, index, conflicts, gaps, sources))
    lines.append("")

    if answer.timeline:
        lines.append("## Timeline")
        lines.append("")
        for event in answer.timeline:
            lines.append(f"- **{event.when.display or 'undated'}** — {event.title}"
                         + (f" ({event.description})" if event.description else ""))
        lines.append("")

    lines.append("## Attribution")
    lines.append("")
    for entry in answer.attribution:
        parts = [f"{entry.author}, *{entry.title}*"]
        if entry.date_display and entry.date_display != "undated":
            parts.append(f"({entry.date_display})")
        if entry.license_id:
            parts.append(f"[{entry.license_id}]")
        if entry.url:
            parts.append(entry.url)
        lines.append("- " + " · ".join(parts))
        if entry.attribution_text:
            lines.append(f"  - {entry.attribution_text}")
    lines.append("")
    lines.append(
        f"_Generated by art-context-engine ({answer.model}) on "
        f"{answer.generated_at:%Y-%m-%d}. Sources are dated and attributed above; "
        "quotation limits were applied per source licence._"
    )
    return "\n".join(lines)


def _block_markdown(
    block: Block,
    answer: Answer,
    index: dict[str, int],
    conflicts: dict[str, Conflict],
    gaps: dict[str, object],
    sources: dict[str, Source],
) -> list[str]:
    pins = _pins(block.source_ids, index)

    if block.kind == BlockKind.QUOTE:
        return [f"> {block.text}", "", f"*Quoted verbatim.{pins}*", ""]

    if block.kind == BlockKind.CONFLICT:
        out = [f"**{block.text}**", ""]
        for conflict_id in block.conflict_ids:
            conflict = conflicts.get(conflict_id)
            if conflict is None:
                continue
            out.extend(_conflict_markdown(conflict, sources))
        return out

    if block.kind == BlockKind.GAP:
        return [f"**What is missing.** {block.text}", ""]

    if block.kind == BlockKind.THESIS:
        return [f"**{block.text}**{pins}", ""]

    return [f"{block.text}{pins}", ""]


def _conflict_markdown(conflict: Conflict, sources: dict[str, Source]) -> list[str]:
    if conflict.kind == ConflictKind.INTERPRETIVE:
        header = f"*Readings differ — {conflict.question}*"
    else:
        header = f"*Conflict ({conflict.severity.value}, {conflict.kind.value}) — {conflict.question}*"
    out = [header, ""]
    for position in conflict.positions:
        source = sources.get(position.source_id)
        label = f"{position.source_title} ({position.authority.value.title()})"
        shown = _gated_span(source, position.span) if source else None
        value = position.value_text or shown or ""
        if shown and shown != value:
            out.append(f"- **{value}** — {label}: “{shown}”")
        else:
            out.append(f"- **{value}** — {label}")
    resolution = (
        "Unresolved. Both positions are shown; neither is deleted."
        if conflict.resolution.value == "UNRESOLVED"
        else f"Resolution: {conflict.resolution.value}."
    )
    out.append(f"- → {resolution}")
    out.append("")
    return out


def _gated_span(source: Source | None, span: Span) -> str | None:
    if source is None:
        return None
    return rights.gate_span(source, span.start, span.end, for_export=True)


# ═══════════════════════════════════════════════════════════════════════════
# PUBLIC / GATED SHAPE
# ═══════════════════════════════════════════════════════════════════════════

def public_answer(
    answer: Answer,
    sources: dict[str, Source],
    *,
    jurisdiction: str | None = None,
) -> Answer:
    """The answer is already safe to serialise, and this asserts why.

    Two invariants hold at assembly time: every `Block.text` is prose written by
    the assembler (never a copy of `source.text`), and every verbatim passage
    went through `rights.gate` in `build_quote`. There is therefore no field on
    an Answer that needs post-hoc stripping — which is the point of gating at
    build time instead of at render time.

    Claim spans do carry source text, but claims live in the pack, not the
    answer; `to_jsonable()` sanitises them before they leave the process.
    """
    return answer


def _sanitize_conflicts(conflicts: list[Conflict], sources: dict[str, Source]) -> list[dict]:
    """Conflict positions carry spans; strip any span the licence forbids."""
    out = []
    for conflict in conflicts:
        data = conflict.model_dump(mode="json")
        for position in data["positions"]:
            source = sources.get(position["source_id"])
            span = position.get("span") or {}
            if source is None or span.get("text") is None:
                continue
            allowed = rights.gate_span(
                source, span["start"], span["end"], for_export=True
            )
            if allowed is None:
                span["text"] = ""
                span["text_withheld"] = "rights policy"
        out.append(data)
    return out


def public_deepening(
    deepening: Deepening,
    sources: dict[str, Source],
    *,
    jurisdiction: str | None = None,
) -> Deepening:
    quotes = []
    for quote in deepening.quotes:
        source = sources.get(quote.source_id)
        text = (
            rights.gate_span(source, quote.span.start, quote.span.end)
            if source else None
        )
        if text:
            quotes.append(quote.model_copy(update={"text": text}))
    return deepening.model_copy(update={"quotes": quotes})


# ═══════════════════════════════════════════════════════════════════════════
# JSON
# ═══════════════════════════════════════════════════════════════════════════

def to_jsonable(answer: Answer, pack: ContextPack, sources: dict[str, Source]) -> dict:
    """The export shape: answer + evidence + rights, one object."""
    public = public_answer(answer, sources)
    return {
        "answer": public.model_dump(mode="json"),
        "conflicts": _sanitize_conflicts(pack.conflicts, sources),
        "gaps": [g.model_dump(mode="json") for g in pack.gaps],
        "sources": [
            {
                "id": s.id,
                "title": s.title,
                "author": s.author,
                "authority": s.authority.value,
                "type": s.type.value,
                "date_document": s.date_document.model_dump(mode="json") if s.date_document else None,
                "url": s.url,
                "rights": {
                    "status": s.rights.status.value,
                    "display_policy": s.rights.display_policy.value,
                    "license_id": s.rights.license_id,
                    "storage_allowed": s.rights.storage_allowed,
                    "redistribution_allowed": s.rights.redistribution_allowed,
                    "attribution_text": s.rights.attribution_text,
                },
                # Stored text is never exported; quotes come from the answer.
                "text_included": False,
            }
            for s in sources.values()
        ],
        "attribution": [a.model_dump(mode="json") for a in answer.attribution],
    }


def rights_report(sources: dict[str, Source]) -> dict:
    """Operational view (§10 metric 9): what each source permits."""
    return {
        sid: {
            "policy": s.rights.display_policy.value,
            "status": s.rights.status.value,
            "storage": s.rights.storage_allowed,
            "redistribution": s.rights.redistribution_allowed,
            "chars_stored": len(s.text or ""),
        }
        for sid, s in sources.items()
    }
